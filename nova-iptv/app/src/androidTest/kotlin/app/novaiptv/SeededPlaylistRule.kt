package app.novaiptv

import app.novaiptv.core.common.AppResult
import kotlinx.coroutines.runBlocking
import mockwebserver3.Dispatcher
import mockwebserver3.MockResponse
import mockwebserver3.MockWebServer
import mockwebserver3.RecordedRequest
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.rules.ExternalResource
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale
import java.util.TimeZone

/** One generated channel of the seeded playlist. */
data class SeedChannel(val name: String, val group: String, val epgId: String?, val broken: Boolean = false) {
    /** Title of the programme airing now (null when the channel has no guide data). */
    val nowTitle: String? get() = epgId?.let { "$name Live Show" }

    /** Title of the programme that starts in 30 minutes. */
    val nextTitle: String? get() = epgId?.let { "$name Late Edition" }
}

/**
 * Seeds the app before the activity starts: clears all data, serves a generated M3U (10 channels
 * in 3 groups) and an XMLTV guide around "now" from a MockWebServer on the device, imports both
 * through the app's own process-wide [app.novaiptv.core.data.DataGraph] (the one the UI uses) and
 * makes the playlist active. Everything is cleared again afterwards.
 *
 * Streams point at Apple's public HLS sample, except [SeedChannel.broken] channels, whose stream
 * URL answers 404 from the mock server.
 */
class SeededPlaylistRule : ExternalResource() {

    lateinit var server: MockWebServer
        private set
    var playlistId: Long = 0
        private set
    var epgProgrammes: Int = 0
        private set

    private val now = System.currentTimeMillis()

    override fun before() {
        TestData.clearAll()
        server = MockWebServer()
        server.dispatcher = object : Dispatcher() {
            override fun dispatch(request: RecordedRequest): MockResponse = when (request.url.encodedPath) {
                "/playlist.m3u" -> MockResponse.Builder().setHeader("Content-Type", "audio/x-mpegurl").body(m3u()).build()
                "/epg.xml" -> MockResponse.Builder().setHeader("Content-Type", "application/xml").body(xmltv()).build()
                else -> MockResponse.Builder().code(404).body("not found").build()
            }
        }
        server.start()
        runBlocking {
            val graph = TestData.appGraph
            val result = graph.playlists.addM3uUrl(PLAYLIST_NAME, server.url("/playlist.m3u").toString(), server.url("/epg.xml").toString())
            assertTrue("seed import failed: $result", result is AppResult.Ok)
            val summary = (result as AppResult.Ok).value
            assertEquals(CHANNELS.size, summary.channels)
            assertEquals(GROUPS.size, summary.groups)
            playlistId = summary.playlistId
            graph.preferences.setActivePlaylist(playlistId)
            val epg = graph.epg.refresh(playlistId)
            assertTrue("seed EPG refresh failed: $epg", epg is AppResult.Ok && epg.value > 0)
            epgProgrammes = (epg as AppResult.Ok).value
        }
        TestData.log("seed: ${CHANNELS.size} channels in ${GROUPS.size} groups, $epgProgrammes EPG programmes, playlist=$playlistId")
    }

    override fun after() {
        runCatching { server.close() }
        TestData.clearAll()
    }

    private fun m3u(): String = buildString {
        append("#EXTM3U\n")
        for (c in CHANNELS) {
            val tvgId = c.epgId?.let { " tvg-id=\"$it\"" }.orEmpty()
            append("#EXTINF:-1$tvgId group-title=\"${c.group}\",${c.name}\n")
            append(if (c.broken) server.url("/streams/${c.name.replace(' ', '_')}.m3u8").toString() else TestData.PUBLIC_HLS + "?ch=" + c.name.replace(' ', '_'))
            append('\n')
        }
    }

    private fun xmltvTime(millis: Long): String =
        SimpleDateFormat("yyyyMMddHHmmss Z", Locale.US).apply { timeZone = TimeZone.getTimeZone("UTC") }.format(Date(millis))

    private fun programme(channel: String, start: Long, end: Long, title: String) =
        """<programme start="${xmltvTime(start)}" stop="${xmltvTime(end)}" channel="$channel"><title lang="en">$title</title><desc>Generated by the UI test</desc></programme>"""

    private fun xmltv(): String {
        val half = 30 * 60_000L
        return buildString {
            append("""<?xml version="1.0" encoding="UTF-8"?>""").append('\n')
            append("""<tv generator-info-name="nova-ui-qa">""").append('\n')
            for (c in CHANNELS) {
                val id = c.epgId ?: continue
                append("""<channel id="$id"><display-name>${c.name}</display-name></channel>""").append('\n')
            }
            for (c in CHANNELS) {
                val id = c.epgId ?: continue
                append(programme(id, now - half, now + half, c.nowTitle!!)).append('\n')
                append(programme(id, now + half, now + 4 * half, c.nextTitle!!)).append('\n')
                append(programme(id, now + 4 * half, now + 8 * half, "${c.name} Night Movie")).append('\n')
            }
            append("</tv>\n")
        }
    }

    companion object {
        const val PLAYLIST_NAME = "Nova UI QA"

        val CHANNELS: List<SeedChannel> = listOf(
            SeedChannel("Alpha News", "News", "alpha.news"),
            SeedChannel("Bravo News", "News", "bravo.news"),
            SeedChannel("Charlie News", "News", "charlie.news"),
            SeedChannel("Delta News", "News", "delta.news"),
            SeedChannel("Echo Sports", "Sports", "echo.sports"),
            SeedChannel("Foxtrot Sports", "Sports", "foxtrot.sports"),
            SeedChannel("Golf Sports", "Sports", "golf.sports"),
            SeedChannel("Hotel Movies", "Movies", "hotel.movies"),
            SeedChannel("India Movies", "Movies", "india.movies"),
            SeedChannel("Juliet Broken", "Movies", null, broken = true),
        )

        /** Group name -> channel count, in playlist order. */
        val GROUPS: Map<String, Int> = CHANNELS.groupingBy { it.group }.eachCount()

        fun inGroup(group: String) = CHANNELS.filter { it.group == group }
    }
}
