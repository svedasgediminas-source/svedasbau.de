package app.novaiptv

import androidx.test.ext.junit.runners.AndroidJUnit4
import app.novaiptv.core.common.AppError
import app.novaiptv.core.common.AppResult
import app.novaiptv.core.data.DataGraph
import app.novaiptv.core.model.ContentType
import app.novaiptv.core.model.PlaylistSource
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.runBlocking
import mockwebserver3.Dispatcher
import mockwebserver3.MockResponse
import mockwebserver3.MockWebServer
import mockwebserver3.RecordedRequest
import org.junit.After
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale
import java.util.TimeZone

/**
 * End-to-end data layer test on the device: a MockWebServer (on localhost, plain http) serves an
 * M3U playlist and an XMLTV guide; the real [DataGraph] (Room on disk, DataStore, OkHttp)
 * imports them. A second [DataGraph] on the same files simulates an app restart.
 */
@RunWith(AndroidJUnit4::class)
class EndToEndDataTest {

    private lateinit var server: MockWebServer
    private val now = System.currentTimeMillis()

    private val m3u = """
        #EXTM3U
        #EXTINF:-1 tvg-id="nova.one" tvg-name="Nova One" tvg-logo="http://logos.example.com/one.png" group-title="News",Nova One
        ${TestData.PUBLIC_HLS}
        #EXTINF:-1 tvg-id="nova.two" tvg-logo="http://logos.example.com/two.png" group-title="Sports",Nova Two
        ${TestData.PUBLIC_HLS}?ch=2
        #EXTINF:-1 tvg-id="nova.three" group-title="News",Nova Three
        ${TestData.PUBLIC_HLS}?ch=3
    """.trimIndent() + "\n"

    private fun xmltvTime(millis: Long): String =
        SimpleDateFormat("yyyyMMddHHmmss Z", Locale.US).apply { timeZone = TimeZone.getTimeZone("UTC") }.format(Date(millis))

    private fun programme(channel: String, start: Long, end: Long, title: String) =
        """<programme start="${xmltvTime(start)}" stop="${xmltvTime(end)}" channel="$channel"><title lang="en">$title</title><desc>Generated by the QA test</desc></programme>"""

    private val xmltv: String by lazy {
        val half = 30 * 60_000L
        buildString {
            append("""<?xml version="1.0" encoding="UTF-8"?>""").append('\n')
            append("""<tv generator-info-name="nova-qa">""").append('\n')
            append("""<channel id="nova.one"><display-name>Nova One</display-name></channel>""").append('\n')
            append("""<channel id="nova.two"><display-name>Nova Two</display-name></channel>""").append('\n')
            append(programme("nova.one", now - half, now + half, "Morning News")).append('\n')
            append(programme("nova.one", now + half, now + 3 * half, "Weather Update")).append('\n')
            append(programme("nova.two", now - half, now + half, "Live Match")).append('\n')
            append(programme("nova.two", now + half, now + 3 * half, "Highlights")).append('\n')
            append("</tv>\n")
        }
    }

    @Before
    fun setUp() {
        TestData.clearAll()
        server = MockWebServer()
        server.dispatcher = object : Dispatcher() {
            override fun dispatch(request: RecordedRequest): MockResponse = when (request.url.encodedPath) {
                "/playlist.m3u" -> MockResponse.Builder().setHeader("Content-Type", "audio/x-mpegurl").body(m3u).build()
                "/epg.xml" -> MockResponse.Builder().setHeader("Content-Type", "application/xml").body(xmltv).build()
                "/garbage.m3u" -> MockResponse.Builder().body("<html><body>This is not a playlist</body></html>").build()
                "/empty.m3u" -> MockResponse.Builder().body("").build()
                else -> MockResponse.Builder().code(404).body("not found").build()
            }
        }
        server.start()
    }

    @After
    fun tearDown() {
        server.close()
        TestData.clearAll()
    }

    @Test
    fun importM3uWithEpgFavoriteAndPersistAcrossRestart(): Unit = runBlocking {
        val graph = TestData.appGraph
        val playlistUrl = server.url("/playlist.m3u").toString()
        val epgUrl = server.url("/epg.xml").toString()

        val result = graph.playlists.addM3uUrl("QA playlist", playlistUrl, epgUrl)
        assertTrue("import failed: $result", result is AppResult.Ok)
        val summary = (result as AppResult.Ok).value
        assertEquals(3, summary.channels)
        assertEquals(2, summary.groups)
        val pid = summary.playlistId

        val playlists = graph.playlists.observePlaylists().first()
        assertEquals(1, playlists.size)
        assertEquals("QA playlist", playlists[0].name)
        assertEquals(PlaylistSource.M3uUrl(playlistUrl), playlists[0].source)
        assertEquals(listOf(epgUrl), playlists[0].epgUrls)

        val groups = graph.channels.observeGroups(pid).first()
        assertEquals(mapOf("News" to 2, "Sports" to 1), groups.associate { it.name to it.channelCount })

        val channels = graph.channels.observeChannels(pid, null).first()
        assertEquals(listOf("Nova One", "Nova Two", "Nova Three"), channels.map { it.name })
        val one = channels[0]
        assertEquals("News", one.groupName)
        assertEquals("nova.one", one.epgId)
        assertEquals("http://logos.example.com/one.png", one.logoUrl)
        assertEquals(TestData.PUBLIC_HLS, one.stream.url)
        assertEquals(listOf("Nova One", "Nova Three"), graph.channels.observeChannels(pid, "News").first().map { it.name })

        // The import schedules an EPG refresh in the background; run one explicitly (serialised by a mutex).
        val epg = graph.epg.refresh(pid)
        assertTrue("EPG refresh failed: $epg", epg is AppResult.Ok && epg.value > 0)
        val nowNext = graph.epg.observeNowNext(listOf("nova.one", "nova.two", "nova.three"), System.currentTimeMillis()).first()
        assertEquals("Morning News", nowNext["nova.one"]?.now?.title)
        assertEquals("Weather Update", nowNext["nova.one"]?.next?.title)
        assertEquals("Live Match", nowNext["nova.two"]?.now?.title)
        assertTrue("no EPG expected for nova.three: $nowNext", nowNext["nova.three"]?.now == null)

        assertTrue(graph.favorites.toggle(ContentType.Channel, one.id, pid))
        assertEquals(listOf(one.id), graph.favorites.observeFavorites(ContentType.Channel).first().map { it.contentId })
        assertTrue(graph.favorites.observeIsFavorite(ContentType.Channel, one.id).first())
        TestData.log("e2e import: ${summary.channels} channels, ${summary.groups} groups, ${(epg as AppResult.Ok).value} EPG programmes, favourite=${one.id}")

        // "Restart": a brand-new graph (new Room instance on the same database file).
        val restarted = DataGraph(TestData.app)
        val playlistsAfter = restarted.playlists.observePlaylists().first()
        assertEquals(listOf(pid), playlistsAfter.map { it.id })
        assertEquals(PlaylistSource.M3uUrl(playlistUrl), playlistsAfter[0].source)
        assertNotNull(playlistsAfter[0].lastRefreshedAtMillis)
        assertEquals(3, restarted.channels.observeChannels(pid, null).first().size)
        assertEquals(listOf(one.id), restarted.favorites.observeFavorites(ContentType.Channel).first().map { it.contentId })
        val nowNextAfter = restarted.epg.observeNowNext(listOf("nova.one"), System.currentTimeMillis()).first()
        assertEquals("Morning News", nowNextAfter["nova.one"]?.now?.title)

        // Toggling again removes the favourite, visible through the restarted graph as well.
        assertTrue(!graph.favorites.toggle(ContentType.Channel, one.id, pid))
        assertTrue(restarted.favorites.observeFavorites(ContentType.Channel).first().isEmpty())
        TestData.log("e2e restart: playlist, channels, favourite and EPG persisted")
    }

    @Test
    fun invalidPlaylistContentFailsCleanly(): Unit = runBlocking {
        val graph = TestData.appGraph
        val garbage = graph.playlists.addM3uUrl("Garbage", server.url("/garbage.m3u").toString(), null)
        assertTrue("expected an error, got $garbage", garbage is AppResult.Err)
        val empty = graph.playlists.addM3uUrl("Empty", server.url("/empty.m3u").toString(), null)
        assertTrue("expected an error, got $empty", empty is AppResult.Err)
        val missing = graph.playlists.addM3uUrl("Missing", server.url("/missing.m3u").toString(), null)
        assertEquals(AppError.Http::class, (missing as AppResult.Err).error::class)
        assertEquals(404, (missing.error as AppError.Http).code)
        // A failed add leaves nothing behind.
        assertTrue(graph.playlists.observePlaylists().first().isEmpty())
        TestData.log("invalid content: garbage=${(garbage as AppResult.Err).error} empty=${(empty as AppResult.Err).error} missing=${missing.error}")
    }

    @Test
    fun invalidUrlIsRejectedAsInvalidInput(): Unit = runBlocking {
        val graph = TestData.appGraph
        for (url in listOf("not a url", "javascript:alert(1)", "ftp://example.com/list.m3u", "", "http://")) {
            val r = graph.playlists.addM3uUrl("Bad", url, null)
            assertTrue("'$url' -> $r", r is AppResult.Err && r.error is AppError.InvalidInput)
        }
        val badEpg = graph.playlists.addM3uUrl("Bad EPG", server.url("/playlist.m3u").toString(), "file:///etc/hosts")
        assertTrue("bad EPG url -> $badEpg", badEpg is AppResult.Err && badEpg.error is AppError.InvalidInput)
        assertTrue(graph.playlists.observePlaylists().first().isEmpty())
        // A refused connection is a network error, not a crash.
        val refused = graph.playlists.addM3uUrl("Refused", "http://127.0.0.1:1/list.m3u", null)
        assertTrue("refused -> $refused", refused is AppResult.Err && refused.error is AppError.Network)
    }
}
